// ============================================================================
// 模块：MapUpdater 实现
// ============================================================================
// 职责：
//   实现地图更新的多线程调度系统
//   提供高性能的地图并行更新能力
//
// 核心类：
//   - MapUpdateRequest：封装单个地图的更新任务
//   - MapUpdater：管理线程池和任务队列
//
// 工作流程：
//   1. 主线程在 World::Update() 中对每个地图调用 schedule_update()
//   2. 任务被封装成 MapUpdateRequest 并推入队列
//   3. 工作线程从队列中取出任务并执行 Map::Update()
//   4. 任务完成后通知主线程
//   5. 主线程调用 wait() 等待所有任务完成
//
// 性能特点：
//   - 利用多核 CPU 并行处理多个地图
//   - 非阻塞任务提交，提高主循环效率
//   - 生产者-消费者队列实现线程间通信
// ============================================================================

#include "MapUpdater.h"
#include "DatabaseEnv.h"
#include "Map.h"
#include "Metric.h"

#include <mutex>

// ============================================================================
// MapUpdateRequest - 地图更新请求封装
// ============================================================================
// 职责：封装单个地图的更新任务，包含地图引用和时间差
// 设计：轻量级任务对象，由工作线程执行后删除
// ============================================================================
class MapUpdateRequest
{
    private:

        Map& m_map;              // 要更新的地图对象引用
        MapUpdater& m_updater;   // MapUpdater 引用，用于通知任务完成
        uint32 m_diff;           // 时间差（毫秒），表示自上次更新以来的时间间隔

    public:

        // ========================================================================
        // 构造函数
        // ========================================================================
        // @brief 初始化地图更新请求
        // @param m - 要更新的地图对象引用
        // @param u - MapUpdater 引用，用于任务完成回调
        // @param d - 时间差（毫秒），从上次更新到现在的时间
        // ========================================================================
        MapUpdateRequest(Map& m, MapUpdater& u, uint32 d)
            : m_map(m), m_updater(u), m_diff(d)
        {
        }

        // ========================================================================
        // 执行地图更新
        // ========================================================================
        // @brief 执行实际的地图更新操作，包括性能监控和完成通知
        // @param 无
        // @return 无
        // 执行流程：
        //   1. 启动性能计时器（记录地图更新耗时）
        //   2. 调用 Map::Update() 执行地图逻辑
        //   3. 通知 MapUpdater 任务完成
        // 调用时机：由工作线程在 WorkerThread() 中调用
        // 注意：
        //   - 性能计时器会自动记录到监控系统
        //   - update_finished() 必须调用，否则主线程会永久阻塞
        // ========================================================================
        void call()
        {
            // 性能监控：记录每个地图的更新时间
            TC_METRIC_TIMER("map_update_time_diff", TC_METRIC_TAG("map_id", std::to_string(m_map.GetId())));

            // 执行地图的核心更新逻辑（处理生物、游戏对象、玩家等）
            m_map.Update (m_diff);

            // 通知线程池任务已完成（减少 pending_requests 计数）
            m_updater.update_finished();
        }
};

// ============================================================================
// 激活线程池
// ============================================================================
// @brief 创建指定数量的工作线程，开始处理地图更新任务
// @param num_threads - 要创建的工作线程数量
// @return 无
// 调用时机：服务器启动时，World::SetInitialSettings() 中调用
// 配置：线程数量由配置文件中的 MapUpdate.Threads 决定
// 注意：
//   - 线程创建后立即开始运行，等待任务队列
//   - 必须在调度任何任务前调用此方法
//   - 线程数量建议不超过 CPU 核心数
// ============================================================================
void MapUpdater::activate(size_t num_threads)
{
    // 创建指定数量的工作线程，每个线程执行 WorkerThread() 函数
    for (size_t i = 0; i < num_threads; ++i)
    {
        _workerThreads.push_back(std::thread(&MapUpdater::WorkerThread, this));
    }
}

// ============================================================================
// 停止线程池
// ============================================================================
// @brief 优雅地停止所有工作线程，清理资源
// @param 无
// @return 无
// 调用时机：服务器关闭时
// 执行步骤：
//   1. 设置终止标志，通知工作线程准备退出
//   2. 等待所有已提交的任务完成（防止数据丢失）
//   3. 取消队列，唤醒所有阻塞等待的线程
//   4. 等待所有工作线程退出（join 操作）
// 注意：
//   - 此函数是阻塞的，可能需要较长时间
//   - 必须在服务器关闭前调用，确保数据一致性
// ============================================================================
void MapUpdater::deactivate()
{
    // 设置终止标志，工作线程会在下次检查时退出
    _cancelationToken = true;

    // 等待所有待处理的任务完成
    wait();

    // 取消队列，唤醒所有在 WaitAndPop() 上阻塞的线程
    _queue.Cancel();

    // 等待所有工作线程退出
    for (auto& thread : _workerThreads)
    {
        thread.join();
    }
}

// ============================================================================
// 等待所有任务完成
// ============================================================================
// @brief 阻塞主线程，直到所有地图更新任务完成
// @param 无
// @return 无
// 调用时机：World::Update() 中提交所有地图任务后调用
// 工作原理：
//   - 使用条件变量等待 pending_requests 变为 0
//   - 每当有任务完成（update_finished()），会通知条件变量
//   - 醒来后重新检查 pending_requests，防止虚假唤醒
// 注意：
//   - 必须调用此函数确保所有地图更新完成
//   - 如果没有任务，此函数会立即返回
// 性能：在等待期间释放锁，允许工作线程继续添加任务
// ============================================================================
void MapUpdater::wait()
{
    std::unique_lock<std::mutex> lock(_lock);

    // 循环等待，直到所有任务完成
    // 使用 while 防止虚假唤醒
    while (pending_requests > 0)
        _condition.wait(lock);

    lock.unlock();
}

// ============================================================================
// 调度地图更新任务
// ============================================================================
// @brief 将一个地图的更新任务提交到线程池队列
// @param map - 要更新的地图对象引用
// @param diff - 时间差（毫秒），从上次更新到现在的时间
// @return 无
// 调用时机：World::Update() 中对每个地图调用
// 执行流程：
//   1. 加锁保护共享变量 pending_requests
//   2. 增加待处理任务计数
//   3. 创建 MapUpdateRequest 对象并推入队列
// 注意：
//   - 此函数是非阻塞的，任务异步执行
//   - 任务对象在堆上分配，由工作线程负责删除
//   - 队列是线程安全的，无需额外加锁
// 性能：O(1) 操作，快速返回不阻塞主线程
// ============================================================================
void MapUpdater::schedule_update(Map& map, uint32 diff)
{
    std::lock_guard<std::mutex> lock(_lock);

    // 增加待处理任务计数（需要在 update_finished() 中减少）
    ++pending_requests;

    // 创建任务对象并推入生产者-消费者队列
    // 队列会唤醒一个等待的工作线程
    _queue.Push(new MapUpdateRequest(map, *this, diff));
}

// ============================================================================
// 检查线程池是否已激活
// ============================================================================
// @brief 返回线程池是否有活跃的工作线程
// @param 无
// @return true - 已激活（有线程），false - 未激活（无线程）
// 用途：
//   - 在调度任务前检查线程池状态
//   - 如果未激活，地图更新会在主线程同步执行
// ============================================================================
bool MapUpdater::activated()
{
    return _workerThreads.size() > 0;
}

// ============================================================================
// 通知单个任务完成
// ============================================================================
// @brief 由 MapUpdateRequest 调用，表示一个地图更新任务完成
// @param 无
// @return 无
// 执行流程：
//   1. 加锁保护共享变量 pending_requests
//   2. 减少待处理任务计数
//   3. 通知条件变量（唤醒可能正在等待的主线程）
// 调用时机：MapUpdateRequest::call() 执行完毕时调用
// 线程安全：此函数由工作线程调用，需要加锁保护共享变量
// 注意：
//   - 每次调度任务增加计数，完成任务减少计数
//   - notify_all() 会唤醒所有等待的线程，包括主线程
// ============================================================================
void MapUpdater::update_finished()
{
    std::lock_guard<std::mutex> lock(_lock);

    // 减少待处理任务计数
    --pending_requests;

    // 通知等待的主线程（如果 pending_requests 变为 0，wait() 会返回）
    _condition.notify_all();
}

// ============================================================================
// 工作线程主函数
// ============================================================================
// @brief 工作线程的主循环函数，从队列中取出并执行地图更新任务
// @param 无
// @return 无
// 运行模式：无限循环，直到收到终止信号
// 执行流程：
//   1. 启用数据库同步查询警告
//   2. 循环从队列获取任务
//   3. 检查终止信号，准备退出
//   4. 执行地图更新任务
//   5. 删除任务对象
// 线程安全：
//   - 队列操作是线程安全的
//   - 数据库连接使用线程本地存储
// 注意：
//   - 工作线程不应执行阻塞的同步数据库查询
//   - 如果检测到同步查询，会记录警告日志
//   - 任务对象由工作线程负责删除
// ============================================================================
void MapUpdater::WorkerThread()
{
    // ========================================================================
    // 启用数据库同步查询警告
    // ========================================================================
    // 工作线程应该避免执行阻塞的数据库查询，因为这会严重影响性能
    // 如果检测到同步查询，会记录警告日志帮助开发者优化
    // ========================================================================
    LoginDatabase.WarnAboutSyncQueries(true);
    CharacterDatabase.WarnAboutSyncQueries(true);
    WorldDatabase.WarnAboutSyncQueries(true);

    // 主循环：持续处理任务直到收到终止信号
    while (true)
    {
        MapUpdateRequest* request = nullptr;

        // ====================================================================
        // 从队列中阻塞等待并获取一个任务
        // ====================================================================
        // WaitAndPop 是阻塞的：
        //   - 如果队列为空，线程会休眠等待
        //   - 当有任务入队时，会被唤醒
        //   - 当队列被取消时，会返回 false
        // ====================================================================
        _queue.WaitAndPop(request);

        // ====================================================================
        // 检查终止信号
        // ====================================================================
        // 在取出任务后检查，确保队列中的任务能被处理完
        // 如果设置了 _cancelationToken，退出循环
        // ====================================================================
        if (_cancelationToken)
            return;

        // ====================================================================
        // 执行地图更新任务
        // ====================================================================
        // call() 内部会：
        //   1. 调用 Map::Update() 更新地图逻辑
        //   2. 调用 update_finished() 通知任务完成
        // ====================================================================
        request->call();

        // ====================================================================
        // 清理任务对象
        // ====================================================================
        // 任务对象在堆上分配，执行完毕后必须删除
        // 由工作线程负责删除，避免内存泄漏
        // ====================================================================
        delete request;
    }
}
